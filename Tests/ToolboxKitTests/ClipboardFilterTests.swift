import AppKit
import Foundation
import Testing
@testable import ToolboxKit

private let t: NSPasteboard.PasteboardType = .string
private let concealed: NSPasteboard.PasteboardType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
private let autoGen: NSPasteboard.PasteboardType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
private let fileType: NSPasteboard.PasteboardType = .fileURL
private let pngType: NSPasteboard.PasteboardType = .png

private func textContent(_ s: String) -> CapturedContent {
    CapturedContent(kind: .text, text: s, pngData: nil, fileURLs: [], pixelSize: nil,
                    byteLength: s.utf8.count)
}

private func input(types: [NSPasteboard.PasteboardType],
                   content: CapturedContent?,
                   own: String? = nil,
                   top: ClipboardItem? = nil,
                   settings: AppSettings = .default,
                   frontApp: String? = nil,
                   paused: Bool = false) -> CaptureInput {
    CaptureInput(types: types, ownWriteMarker: own, candidate: content, currentTop: top,
                 frontAppBundleID: frontApp, paused: paused, settings: settings,
                 now: Date(timeIntervalSince1970: 1_700_000_000))
}

// MARK: 安全底线

@Test func concealedPasswordCopyIsNeverStored() {
    // 1Password / Bitwarden / KeePassXC 复制密码时统一打这个标记
    let d = ClipboardFilter.decide(input(types: [t, concealed], content: textContent("hunter2")))
    #expect(d == .ignore(.concealed))
}

@Test func concealedOutranksEverythingExceptPause() {
    // 即使已暂停、即使是自己写的，concealed 也要报 concealed 而不是别的理由
    let d = ClipboardFilter.decide(input(types: [t, concealed], content: textContent("x"),
                                         own: "mine", paused: true))
    #expect(d == .ignore(.paused))       // 暂停优先（用户显式意图）
    let d2 = ClipboardFilter.decide(input(types: [t, concealed], content: textContent("x"),
                                          own: "mine"))
    #expect(d2 == .ignore(.concealed))   // 未暂停时 concealed 优先于自写标记
}

@Test func ownWriteMarkerIsIgnored() {
    let d = ClipboardFilter.decide(input(types: [t], content: textContent("x"), own: "item-1"))
    #expect(d == .ignore(.ourOwnWrite))
}

@Test func blockedAppIsIgnoredBeforeContentChecks() {
    var s = AppSettings.default
    s.blockedApps = ["com.agilebits.onepassword7"]
    let d = ClipboardFilter.decide(input(types: [t], content: textContent("x"),
                                         settings: s, frontApp: "com.agilebits.onepassword7"))
    #expect(d == .ignore(.blockedApp("com.agilebits.onepassword7")))
}

// MARK: 内容判定

@Test func emptyAndOversizedAreIgnored() {
    #expect(ClipboardFilter.decide(input(types: [t], content: textContent(""))) == .ignore(.empty))
    #expect(ClipboardFilter.decide(input(types: [t], content: textContent("   "))) == .ignore(.empty))
    var s = AppSettings.default
    s.maxTextBytes = 10
    let big = textContent(String(repeating: "a", count: 11))
    #expect(ClipboardFilter.decide(input(types: [t], content: big, settings: s)) == .ignore(.tooLarge))
}

@Test func sameAsTopBumpsInsteadOfInserting() {
    let top = ClipboardItem(text: "dup", sourceBundleID: nil, sourceAppName: nil,
                            at: Date(timeIntervalSince1970: 1))
    let d = ClipboardFilter.decide(input(types: [t], content: textContent("dup"), top: top))
    #expect(d == .ignore(.sameAsTop))
}

@Test func sameAsTopComparesURLsNotJustText() {
    let urls = [URL(fileURLWithPath: "/tmp/a"), URL(fileURLWithPath: "/tmp/b")]
    let top = ClipboardItem(fileURLs: urls, sourceBundleID: nil, sourceAppName: nil,
                            at: Date(timeIntervalSince1970: 1))
    let same = CapturedContent(kind: .fileURLs, text: nil, pngData: nil, fileURLs: urls,
                               pixelSize: nil, byteLength: 2)
    #expect(ClipboardFilter.decide(input(types: [fileType], content: same, top: top)) == .ignore(.sameAsTop))
    let different = CapturedContent(kind: .fileURLs, text: nil, pngData: nil,
                                    fileURLs: [URL(fileURLWithPath: "/tmp/c")],
                                    pixelSize: nil, byteLength: 1)
    if case .accept = ClipboardFilter.decide(input(types: [fileType], content: different, top: top)) {
    } else { Issue.record("不同文件列表应接受") }
}

@Test func imageOverMaxPixelsIsIgnored() {
    var s = AppSettings.default
    s.maxImagePixels = 1000
    let big = CapturedContent(kind: .image, text: nil, pngData: Data([1]),
                              fileURLs: [], pixelSize: CGSize(width: 100, height: 100),
                              byteLength: 1)
    #expect(ClipboardFilter.decide(input(types: [pngType], content: big, settings: s)) == .ignore(.tooLarge))
}

@Test func autoGeneratedFollowsSetting() {
    let i = input(types: [t, autoGen], content: textContent("x"))
    if case .accept = ClipboardFilter.decide(i) { } else { Issue.record("默认应记录") }
    var s = AppSettings.default
    s.recordAutoGenerated = false
    #expect(ClipboardFilter.decide(input(types: [t, autoGen], content: textContent("x"),
                                         settings: s)) == .ignore(.autoGenerated))
}

@Test func noCandidateContentMeansIgnore() {
    #expect(ClipboardFilter.decide(input(types: [t], content: nil)) == .ignore(.empty))
}

@Test func pausedIgnoresEverything() {
    let d = ClipboardFilter.decide(input(types: [t], content: textContent("x"), paused: true))
    #expect(d == .ignore(.paused))
}

// MARK: 设置向后兼容（用户机器上已有旧 settings.json）

@Test func oldSettingsFileStillDecodesAndKeepsHotkeys() throws {
    let url = URL(fileURLWithPath: "/tmp/toolbox-oldsettings-\(UUID().uuidString).json")
    defer { try? FileManager.default.removeItem(at: url) }
    // 完全按 M0 版本的字段集写一份，模拟用户的旧文件
    let legacy = """
    {"clipboardCapacity":333,"hotkeys":["clipboard",{"keyCode":9,"carbonModifiers":768}],
     "pinMaxZoom":8,"pinMinZoom":0.2,"scrollZoomDirection":"upMagnifies"}
    """
    try legacy.data(using: .utf8)!.write(to: url)
    let loaded = try SettingsStore(file: url).load()
    #expect(loaded.clipboardCapacity == 333)
    #expect(loaded.hotkeys[.clipboard]?.displayString == "⇧⌘V")
    // 新字段必须回落到默认值，而不是把整个文件判为损坏
    #expect(loaded.maxTextBytes == AppSettings.default.maxTextBytes)
    #expect(loaded.blockedApps == [])
    #expect(loaded.recordAutoGenerated == true)
    #expect(try SettingsStore(file: url).load() == loaded)
}
