import AppKit
import Foundation

/// 从 pasteboard 归一化出来的候选内容。
public struct CapturedContent: Equatable, Sendable {
    public var kind: ClipboardKind
    public var text: String?
    public var pngData: Data?
    public var fileURLs: [URL]
    public var pixelSize: CGSize?
    public var byteLength: Int

    public init(kind: ClipboardKind, text: String?, pngData: Data?, fileURLs: [URL],
                pixelSize: CGSize?, byteLength: Int) {
        self.kind = kind; self.text = text; self.pngData = pngData
        self.fileURLs = fileURLs; self.pixelSize = pixelSize; self.byteLength = byteLength
    }
}

public struct CaptureInput: Sendable {
    public var types: [NSPasteboard.PasteboardType]
    /// pasteboard 上的自写标记值（本 App 写入时带的 itemId）
    public var ownWriteMarker: String?
    public var candidate: CapturedContent?
    public var currentTop: ClipboardItem?
    public var frontAppBundleID: String?
    public var paused: Bool
    public var settings: AppSettings
    public var now: Date

    public init(types: [NSPasteboard.PasteboardType], ownWriteMarker: String?,
                candidate: CapturedContent?, currentTop: ClipboardItem?,
                frontAppBundleID: String?, paused: Bool, settings: AppSettings, now: Date) {
        self.types = types; self.ownWriteMarker = ownWriteMarker
        self.candidate = candidate; self.currentTop = currentTop
        self.frontAppBundleID = frontAppBundleID; self.paused = paused
        self.settings = settings; self.now = now
    }
}

public enum CaptureDecision: Equatable {
    case accept(CapturedContent)
    case ignore(IgnoreReason)

    public enum IgnoreReason: Equatable {
        case paused
        case concealed
        case ourOwnWrite
        case blockedApp(String)
        case autoGenerated
        case empty
        case tooLarge
        case sameAsTop
        case unsupported
    }
}

extension NSPasteboard.PasteboardType {
    /// 业界约定（1Password / Bitwarden / KeePassXC 都实现）：
    /// 带这个标记的内容表示"用户复制的是敏感数据"，任何历史工具都不该记录。
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// 表示"由程序自动生成、不是用户主动复制"。
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// 本 App 自己写入时打的标记，值为 itemId，用于避免采集到自己。
    static let ownWrite = NSPasteboard.PasteboardType("com.ebertwiseman.toolbox.own-write")
}

/// 纯函数：决定一次 pasteboard 变化要不要入库。
///
/// 判定顺序是有意义的，改动必须同步改测试：
/// 1. `paused` 最先 —— 用户的显式意图，且最便宜
/// 2. `concealed` 其次 —— 密码不入库是本模块的安全底线，不能被后面的理由掩盖
/// 3. 自写标记 —— 防自采集循环
/// 4. 来源 App 黑名单 —— 内容还没读就先拒，省开销也少暴露
/// 5. AutoGenerated / 空 / 超限 / 与栈顶相同 —— 内容级判定
public enum ClipboardFilter {

    public static func decide(_ i: CaptureInput) -> CaptureDecision {
        if i.paused { return .ignore(.paused) }
        if i.types.contains(.concealed) { return .ignore(.concealed) }
        if i.ownWriteMarker != nil { return .ignore(.ourOwnWrite) }
        if let app = i.frontAppBundleID, i.settings.blockedApps.contains(app) {
            return .ignore(.blockedApp(app))
        }
        if !i.settings.recordAutoGenerated, i.types.contains(.autoGenerated) {
            return .ignore(.autoGenerated)
        }
        guard let c = i.candidate else { return .ignore(.empty) }

        switch c.kind {
        case .text:
            guard let text = c.text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            else { return .ignore(.empty) }
            if c.byteLength > i.settings.maxTextBytes { return .ignore(.tooLarge) }
        case .image:
            guard let png = c.pngData, !png.isEmpty else { return .ignore(.empty) }
            if let size = c.pixelSize,
               Double(size.width) * Double(size.height) > i.settings.maxImagePixels {
                return .ignore(.tooLarge)
            }
        case .fileURLs:
            guard !c.fileURLs.isEmpty else { return .ignore(.empty) }
            if c.fileURLs.count > i.settings.maxFileEntries { return .ignore(.tooLarge) }
        }

        if isSameAsTop(c, i.currentTop) { return .ignore(.sameAsTop) }
        return .accept(c)
    }

    /// "同一条内容"的判定按类型走各自的语义，不能只比 text：
    /// 图片比 sha，文件比路径列表（顺序敏感，因为粘贴结果会变）。
    static func isSameAsTop(_ c: CapturedContent, _ top: ClipboardItem?) -> Bool {
        guard let top, top.kind == c.kind else { return false }
        switch c.kind {
        case .text:
            return (c.text ?? "") == (top.text ?? "")
        case .image:
            guard let sha = c.shaGuess, let mine = top.mediaSHA256 else { return false }
            return sha == mine
        case .fileURLs:
            return c.fileURLs.map(\.path) == (top.fileURLs?.map(\.path) ?? [])
        }
    }
}

extension CapturedContent {
    /// 图片的 sha 由 MediaStore 在写盘时算，归一化阶段先带着走。
    /// 放在这里是为了让 `CapturedContent` 保持值类型且可 Sendable。
    public var shaGuess: String? { pngData.map { SHA256.hex($0) } }
}
